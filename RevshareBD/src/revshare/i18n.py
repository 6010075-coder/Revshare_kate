MONTH_WORDS = {
    "en": ("month", "months", "months"),
    "ru": ("месяц", "месяца", "месяцев"),
    "uk": ("місяць", "місяці", "місяців"),
    "pl": ("miesiąc", "miesiące", "miesięcy"),
    "hu": ("hónap", "hónap", "hónap"),
    "pt": ("mês", "meses", "meses"),
}


def months_word(language: str, count: int) -> str:
    one, few, many = MONTH_WORDS.get(language, MONTH_WORDS["en"])
    if language in {"ru", "uk", "pl"}:
        tail, tens = count % 10, count % 100
        if tail == 1 and tens != 11:
            return one
        if 2 <= tail <= 4 and not 12 <= tens <= 14:
            return few
        return many
    return one if count == 1 else few


def translator(language: str):
    lang = language if language in SUPPORTED_LANGUAGES else "en"

    def translate(key: str, **values: object) -> str:
        text = TRANSLATIONS[lang].get(key) or TRANSLATIONS["en"].get(key) or key
        return text.format(**values) if values else text

    return translate
